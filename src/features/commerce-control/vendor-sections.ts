/** Flat, in menu order — the query list and the lookup both use this. */
export const vendorSections: VendorSection[] = vendorSectionGroups.flatMap(
  (group) => group.sections,
);

export const DEFAULT_VENDOR_SECTION = 'dashboard';

/**
 * A section key can contain a slash, so the route captures the rest of the
 * path with a splat and this resolves it. An unknown key falls back to the
 * default rather than rendering an empty console.
 */
export function resolveVendorSection(path: string | undefined): VendorSection {
  const key = (path ?? "").replace(/^\/+|\/+$/g, "");
  return (
    vendorSections.find((section) => section.key === key) ??
    vendorSections.find((section) => section.key === DEFAULT_VENDOR_SECTION)!
  );
}
